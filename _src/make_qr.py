#!/usr/bin/env python3
"""Generate the WhatsApp QR codes used by the popup.

The QR codes are generated here and committed as static SVG files, so the
published site needs no QR library, no external image service and makes no
third-party request — the page promises no tracking, and a QR fetched from
someone else's API would quietly break that promise.

Needs segno (pure Python, no dependencies of its own):

    python3 -m pip install segno
    python3 _src/make_qr.py
"""
import io, json, os, sys
from urllib.parse import quote

try:
    import segno
except ImportError:
    sys.exit("segno is not installed — run: python3 -m pip install segno")

PHONE = '905337713890'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'assets', 'img', 'qr')

# topic key -> (Turkish subject, English subject)
# Kept short on purpose: a Turkish character costs six to nine characters once
# percent-encoded, and a longer URL means a denser QR. The wording stays
# properly spelled — this message goes out under her name — and still fits in a
# symbol that reads from a phone screen at the size the popup shows it.
TOPICS = {
    'toefl':  ('TOEFL iBT',          'TOEFL iBT'),
    'gre':    ('GRE / GMAT',         'GRE / GMAT'),
    'ielts':  ('IELTS',              'IELTS'),
    'school': ('okul İngilizcesi',   'school English'),
}

SENTENCE = {
    'tr': 'Merhaba, {} için bilgi almak istiyorum.',
    'en': 'Hello, I would like to ask about {}.',
}


def wa_url(topic, lang):
    subject = TOPICS[topic][0 if lang == 'tr' else 1]
    return 'https://wa.me/%s?text=%s' % (PHONE, quote(SENTENCE[lang].format(subject)))


def main():
    os.makedirs(OUT, exist_ok=True)
    rows = []
    links = {}
    for topic in TOPICS:
        links[topic] = {}
        for lang in ('tr', 'en'):
            url = wa_url(topic, lang)
            links[topic][lang] = url
            # error correction M (15%) — the standard for URLs, and it keeps the
            # symbol small enough to stay scannable at the size it is displayed
            qr = segno.make(url, error='m')
            path = os.path.join(OUT, '%s-%s.svg' % (topic, lang))
            qr.save(path, kind='svg', scale=1, border=4,
                    dark='#101a19', light='#ffffff', svgclass=None, lineclass=None,
                    omitsize=True, svgversion=None)
            rows.append((topic, lang, qr.version, qr.symbol_size(1)[0],
                         os.path.getsize(path), len(url)))

    # one source of truth: the popup's links come from the same strings that
    # were encoded into the codes above, so the two can never drift apart
    data = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'assets', 'wa-links.js')
    with io.open(data, 'w', encoding='utf-8') as fh:
        fh.write('/* Generated by _src/make_qr.py — do not edit by hand. */\n')
        fh.write('window.NM_WA = ' + json.dumps(links, ensure_ascii=False, indent=1) + ';\n')
    print('  wa-links.js written (%d bytes)' % os.path.getsize(data))

    w = max(len(t) for t, *_ in rows)
    for topic, lang, ver, size, nbytes, urllen in rows:
        print('  %-*s %s  v%-2d %2dx%-2d modules  %5d bytes  (url %d chars)'
              % (w, topic, lang, ver, size, size, nbytes, urllen))
    print('%d QR codes written to assets/img/qr/' % len(rows))


if __name__ == '__main__':
    main()
